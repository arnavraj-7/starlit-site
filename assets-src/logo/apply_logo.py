"""Put the chosen logotype (out/logotype-d.json) into the site: a Logo component in Chrome.jsx used in
the masthead, and its CSS. Re-run after re-tuning logotype.py; it replaces the Logo block in place."""
import io, json, re, sys
WEB = 'C:/projects/starlit-site/web/src/'
j = json.load(io.open('C:/projects/starlit-site/assets-src/logo/out/logotype-d.json', encoding='utf-8'))
m = re.search(r'<circle cx="([\d.]+)" cy="([\d.]+)"', j['body'])
RING = f'{float(m.group(1)):g}px {float(m.group(2)):g}px'      # the ring's centre: the satellite orbits it
body = (j['body'].replace('class=', 'className=').replace('stroke-width=', 'strokeWidth=')
        .replace('stroke="#070912"', 'stroke="var(--ink, #070912)"').replace('fill="#ffc496"', 'fill="var(--glint, #ffc496)"'))

BLOCK = ('// --- logo (generated by assets-src/logo/apply_logo.py from logotype.py) ---\n'
         '// Starlit\'s logotype: Geist outlines refined by hand, locked up with the ring mark. The i\'s dot\n'
         '// is a four-point glint (star + lit), the l\'s top is cut on a slant like a stylus tip, and the\n'
         '// spacing is set by eye. One clean outline, so it sits on any background.\n'
         'export function Logo(props) {\n'
         '  return (\n'
         f'    <svg className="logo" viewBox="{j["viewBox"]}" role="img" aria-label="Starlit" {{...props}}>\n'
         f'      {body}\n'
         '    </svg>\n'
         '  )\n'
         '}\n'
         '// --- end logo ---\n')

p = WEB + 'Chrome.jsx'
s = io.open(p, encoding='utf-8', newline='').read()
if '// --- logo (' in s:
    a = s.index('// --- logo ('); b = s.index('// --- end logo ---\n') + len('// --- end logo ---\n')
    s = s[:a] + BLOCK + s[b:]
else:
    anchor = '// violet -> amber -> teal across the seven letters of the name'
    if s.count(anchor) != 1: sys.exit('Chrome.jsx anchor missing')
    s = s.replace(anchor, BLOCK + '\n' + anchor, 1)
io.open(p, 'w', encoding='utf-8', newline='').write(s)
print('Chrome.jsx ok')

p = WEB + 'App.jsx'
s = io.open(p, encoding='utf-8', newline='').read()
old = '<div className="wrap masthead"><span className="brand"><Mark />Starlit</span></div>'
new = '<div className="wrap masthead"><a className="brand" href="#top" aria-label="Starlit"><Logo /></a></div>'
if old in s:
    s = s.replace(old, new, 1)
elif new not in s:
    sys.exit('App.jsx masthead line not found')
imp_old = "import { Mark, Footer } from './Chrome.jsx'"
if imp_old in s:
    # Mark is still used elsewhere?
    rest = s.replace(imp_old, '')
    names = 'Mark, Logo, Footer' if re.search(r'<Mark\b', rest) else 'Logo, Footer'
    s = s.replace(imp_old, f"import {{ {names} }} from './Chrome.jsx'", 1)
io.open(p, 'w', encoding='utf-8', newline='').write(s)
print('App.jsx ok')

p = WEB + 'styles.css'
s = io.open(p, encoding='utf-8', newline='').read()
old = (".brand { display: inline-flex; align-items: center; gap: .5em; font-weight: 800; font-size: clamp(1.2rem, 1.05vw, 1.6rem); letter-spacing: -.02em; text-decoration: none; }\n"
       ".brand svg { width: 1.15em; height: 1.15em; color: var(--accent); filter: drop-shadow(0 0 8px var(--glow)); }\n")
new = """.brand { display: inline-flex; align-items: center; text-decoration: none; color: var(--paper); line-height: 0; }
/* the lockup: type in paper, the ring in the section's colour, the i's glint in warm light */
.brand .logo { height: clamp(26px, 1.75vw, 40px); width: auto; overflow: visible; }
.brand .lg-mark { color: var(--accent); filter: drop-shadow(0 0 8px var(--glow)); }
.brand .lg-glint { transform-box: fill-box; transform-origin: center; filter: drop-shadow(0 0 5px rgb(255 170 106 / .75));
  animation: lg-twinkle 1.1s cubic-bezier(.2, .7, .3, 1) 1.4s both; transition: transform .6s var(--ease), filter .6s var(--ease); }
.brand .lg-sat { transform-box: view-box; transform-origin: RING_ORIGIN; transition: transform .9s var(--ease); }
@media (hover: hover) {
  .brand:hover .lg-glint { transform: rotate(45deg) scale(1.25); filter: drop-shadow(0 0 9px rgb(255 170 106 / .95)); }
  .brand:hover .lg-sat { transform: rotate(38deg); }      /* the satellite moves on round its orbit */
}
@keyframes lg-twinkle { 0% { transform: scale(0) rotate(-90deg); opacity: 0; } 60% { transform: scale(1.35) rotate(10deg); opacity: 1; } 100% { transform: none; opacity: 1; } }
@media (prefers-reduced-motion: reduce) { .brand .lg-glint { animation: none; } .brand .lg-glint, .brand .lg-sat { transition: none; } }
""".replace('RING_ORIGIN', RING)
if old in s:
    s = s.replace(old, new, 1)
elif '.brand .logo {' in s:
    a = s.index('.brand { display: inline-flex'); b = s.index('@media (prefers-reduced-motion: reduce) { .brand .lg-glint')
    b = s.index('\n', b) + 1
    s = s[:a] + new + s[b:]
else:
    sys.exit('styles.css .brand rules not found')
io.open(p, 'w', encoding='utf-8', newline='').write(s)
print('styles.css ok')
